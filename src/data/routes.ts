/** Helper to get localized Route object */
export function getLocalizedRoute(route: Route, lang: Language): Route {
  if (lang === 'en') {
    return {
      ...route,
      name: route.name_en || route.name,
      description: route.description_en || route.description,
      features: route.features_en || route.features,
    };
  }
  if (lang === 'zh') {
    return {
      ...route,
      name: route.name_zh || route.name,
      description: route.description_zh || route.description,
      features: route.features_zh || route.features,
    };
  }
  return route;
}

/** Returns all routes. */
export function getRoutes(): Route[] {
  return ROUTES;
}

/** Returns routes filtered by category. */
export function getRoutesByCategory(category: RouteCategory): Route[] {
  return ROUTES.filter(r => r.category === category);
}

/** Returns a single route by ID, or undefined if not found. */
export function getRouteById(id: string): Route | undefined {
  return ROUTES.find(r => r.id === id);
}
